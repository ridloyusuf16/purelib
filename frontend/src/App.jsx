import { useState, useEffect } from 'react'
import axios from 'axios'

function App() {
  const [books, setBooks] = useState([])
  const [loading, setLoading] = useState(true)

  // Fungsi untuk mengambil data buku dari Backend API
  const fetchBooks = async () => {
    try {
      // Alamat backend API PureLib yang kita buat
      const response = await axios.get('http://127.0.0.1:5001/api/books')
      setBooks(response.data.data)
      setLoading(false)
    } catch (error) {
      console.error('Gagal mengambil data buku:', error)
      setLoading(false)
    }
  }

  // Dipanggil otomatis saat komponen React pertama kali dimuat
  useEffect(() => {
    fetchBooks()
  }, [])

  return (
    <div style={{ padding: '30px', fontFamily: 'sans-serif', maxWidth: '800px', margin: '0 auto' }}>
      <h1>📚 PureLib Dashboard</h1>
      <hr />

      <h2>Koleksi Buku Saya</h2>

      {loading ? (
        <p>Memuat data buku...</p>
      ) : books.length === 0 ? (
        <p>Belum ada koleksi buku di database.</p>
      ) : (
        <ul>
          {books.map((book) => (
            <li key={book._id} style={{ marginBottom: '10px' }}>
              <strong>{book.title}</strong> - {book.author} ({book.status})
            </li>
          ))}
        </ul>
      )}
    </div>
  )
}

export default App